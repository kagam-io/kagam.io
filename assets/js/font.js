// 文字列の幅 (ドット)。字間は1ドット
export const textWidth = (font, str) => [...str].reduce((w, ch) => w + font[ch].rows[0].length + 1, -1);

/*
  文字列を (x, y) から描く。y は大文字の天辺の段。
    shadow:   あれば右下1ドットに影を落とす
    dim:      この位置 (0 始まり) の文字は dimColor で描く
*/
export function drawText(ctx, font, str, x, y, { color, shadow, dim, dimColor } = {}) {
  const paint = (dx, dy, base, useDim) => {
    let cx = x + dx;
    [...str].forEach((ch, i) => {
      ctx.fillStyle = useDim && dim?.includes(i) ? dimColor : base;
      const g = font[ch];
      g.rows.forEach((row, r) => {
        for (let k = 0; k < row.length; k++) if (row[k] === '#') ctx.fillRect(cx + k, y + dy + g.top + r, 1, 1);
      });
      cx += g.rows[0].length + 1;
    });
  };
  if (shadow) paint(1, 1, shadow, false);
  paint(0, 0, color, true);
}
